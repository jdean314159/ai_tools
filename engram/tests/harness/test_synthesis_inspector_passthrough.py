def test_title_to_origin_includes_synthesis():
    """Procedural Rules section must get origin='synthesis' in build_prompt_trace."""
    from engram.project_memory import ProjectMemory

    with tempfile.TemporaryDirectory() as td:
        sm = SemanticMemory(db_path=Path(td))
        _write_rule(sm, "Always use WAL mode on SQLite connections",
                    support=["ep_a", "ep_b", "ep_c"])

        # Inject a mock build_prompt that produces a Procedural Rules section
        mock_result = {
            "prompt": (
                "## Episodic\nSome episodic content.\n\n"
                "## Procedural Rules\n- Always use WAL mode on SQLite connections\n\n"
                "## User\nHow do I configure SQLite?"
            ),
            "prompt_tokens": 50,
            "context": None,
            "compressed": False,
            "memory_tokens": 20,
        }

        # Build a minimal PM with our SemanticMemory injected
        pm = ProjectMemory.__new__(ProjectMemory)
        pm.project_id = "test"
        pm.semantic = sm
        pm.budget = SimpleNamespace(total_prompt_tokens=4096)
        pm._token_counter = lambda t: max(1, len(t) // 4)
        pm.session_id = "sess"

        # Patch build_prompt to return our controlled output
        with patch.object(pm, "build_prompt", return_value=mock_result):
            with patch.object(pm, "_build_synthesis_block",
                              return_value="- Always use WAL mode on SQLite connections"):
                from engram.inspection import PromptBuildTrace
                trace = pm.build_prompt_trace.__func__(
                    pm,
                    "How do I configure SQLite?",
                    _result=mock_result,
                )

        # The Procedural Rules section must have origin="synthesis"
        origins = {s.origin for s in trace.sections}
        assert "synthesis" in origins, \
            f"'synthesis' origin missing from sections. Got: {origins}"

        # Must NOT have "procedural_rules" as autogenerated fallback
        assert "procedural_rules" not in origins, \
            f"'procedural_rules' fallback found — title_to_origin mapping is wrong"


