def test_no_synthesis_section_when_no_rules():
    """When synthesis block is empty, no synthesis section or evidence should appear."""
    from engram.project_memory import ProjectMemory

    mock_result = {
        "prompt": "## Episodic\nSome content.\n\n## User\nA query.",
        "prompt_tokens": 20,
        "context": None,
        "compressed": False,
        "memory_tokens": 10,
    }

    with tempfile.TemporaryDirectory() as td:
        sm = SemanticMemory(db_path=Path(td))  # empty — no rules

        pm = ProjectMemory.__new__(ProjectMemory)
        pm.project_id = "test"
        pm.semantic = sm
        pm.budget = SimpleNamespace(total_prompt_tokens=4096)
        pm._token_counter = lambda t: max(1, len(t) // 4)
        pm.session_id = "sess"

        with patch.object(pm, "build_prompt", return_value=mock_result):
            with patch.object(pm, "_build_synthesis_block", return_value=""):
                trace = pm.build_prompt_trace.__func__(pm, "A query.", _result=mock_result)

        origins = {s.origin for s in trace.sections}
        assert "synthesis" not in origins, \
            f"synthesis section appeared but no rules exist: {origins}"
        synth_ev = [e for e in trace.evidence if e.source == "synthesis"]
        assert len(synth_ev) == 0, \
            f"synthesis evidence appeared but no rules exist: {synth_ev}"
        assert "synthesis" not in trace.token_accounting.per_origin_used, \
            "synthesis token accounting should be absent when no rules"


def test_adapter_section_passthrough():
    """Inspector adapter must pass origin='synthesis' through unchanged."""
    # Test the mapping in _trace_to_inspector_trace directly
    try:
        from llm_inspector.adapters.engram_adapter import _trace_to_inspector_trace
        from llm_inspector.protocols import AugmentRequest
        from llm_inspector.core.types import Turn
        from engram_lite.inspection import (
            PromptBuildTrace, PromptSectionTrace, TokenAccountingTrace
        )
    except ImportError as e:
        print(f"  SKIP  test_adapter_section_passthrough: {e}")
        return

    # Build a minimal trace with a synthesis section
    synth_section = PromptSectionTrace(
        title="Procedural Rules",
        origin="synthesis",
        text="- Use WAL mode always",
        tokens=5,
    )
    user_section = PromptSectionTrace(
        title="User",
        origin="user",
        text="SQLite config?",
        tokens=3,
    )
    trace_obj = PromptBuildTrace(
        sections=[synth_section, user_section],
        evidence=[],
        token_accounting=TokenAccountingTrace(per_origin_used={"synthesis": 5, "user": 3}),
        flags={},
        final_prompt="",
    )

    req = AugmentRequest(
        turn=Turn(role="user", text="SQLite config?", session_id="s1"),
        session_id="s1",
    )
    inspector_trace = _trace_to_inspector_trace(req, trace_obj)

    # Origin must survive the adapter mapping
    origins = {s.origin for s in inspector_trace.context.sections}
    assert "synthesis" in origins, \
        f"'synthesis' origin lost in adapter passthrough. Got: {origins}"
    assert inspector_trace.context.token_accounting.per_origin_used.get("synthesis") == 5, \
        "synthesis token count not preserved by adapter"


